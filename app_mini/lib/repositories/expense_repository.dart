import 'package:sqflite/sqflite.dart';

import '../core/database/local_database.dart';
import '../daos/expense_dao.dart';
import '../models/expense_model.dart';

/* Business logic for expenses.

An expense is a single flat record — no allocation validation, no
child-table transaction. `businessUnitId` is strict scope: every
expense belongs to exactly one store and is immutable after creation.*/
class ExpenseRepository {
  ExpenseRepository(this._localDatabase, this._expenseDao);

  final LocalDatabase _localDatabase;
  final ExpenseDao _expenseDao;

  Future<List<ExpenseModel>> getAllExpenses({
    required int businessUnitId,
    int? supplierId,
    DateTime? startDate,
    DateTime? endDate,
  }) {
    return _expenseDao.getAllExpenses(
      businessUnitId: businessUnitId,
      supplierId: supplierId,
      startDate: startDate,
      endDate: endDate,
    );
  }

  Future<ExpenseModel?> getExpenseById(int idExpense) {
    return _expenseDao.getExpenseById(idExpense);
  }

  Future<Set<int>> getStockLinkedExpenseIds(int businessUnitId) {
    return _expenseDao.getStockLinkedExpenseIds(businessUnitId: businessUnitId);
  }
  
  /* [txn] lets other repositories (e.g. StockRepository) create an expense
  inside their own all-or-nothing transaction. */
  Future<ExpenseModel> createExpense({
    required int businessUnitId,
    int? supplierId,
    required String description,
    required int amountCents,
    required DateTime expenseDate,
    Transaction? txn,
  }) async {
    if (description.trim().isEmpty) {
      throw ArgumentError('Expense description cannot be empty.');
    }
    if (amountCents <= 0) {
      throw ArgumentError('Expense amount must be greater than zero.');
    }

    final expense = ExpenseModel(
      supplierId: supplierId,
      description: description.trim(),
      amountCents: amountCents,
      expenseDate: expenseDate,
      createdAt: DateTime.now(),
      businessUnitId: businessUnitId,
    );

    final id = await _expenseDao.insertExpense(expense, txn: txn);
    return expense.copyWith(idExpense: id);
  }

  Future<ExpenseModel> updateExpense({
    required int idExpense,
    int? supplierId,
    required String description,
    required int amountCents,
    required DateTime expenseDate,
  }) async {
    final existing = await _expenseDao.getExpenseById(idExpense);
    if (existing == null) {
      throw StateError('Expense not found.');
    }
    if (existing.deleted) {
      throw StateError('Cannot update a deleted expense.');
    }
    /* Its amount is quantity x unit cost of a stock movement; editing it
    would desync the two. Correct stock with a counter-movement instead. */
    if (await _expenseDao.isLinkedToStock(idExpense)) {
      throw StateError(
        'This expense was generated by a stock purchase and cannot be edited.',
      );
    }
    if (description.trim().isEmpty) {
      throw ArgumentError('Expense description cannot be empty.');
    }
    if (amountCents <= 0) {
      throw ArgumentError('Expense amount must be greater than zero.');
    }

    final updated = existing.copyWith(
      supplierId: supplierId,
      description: description.trim(),
      amountCents: amountCents,
      expenseDate: expenseDate,
    );

    await _expenseDao.updateExpense(updated);
    return updated;
  }

  Future<void> deleteExpense(int idExpense, String deletionReason) async {
    if (deletionReason.trim().isEmpty) {
      throw ArgumentError('A deletion reason is required.');
    }

    final existing = await _expenseDao.getExpenseById(idExpense);
    if (existing == null) {
      throw StateError('Expense not found.');
    }
    if (existing.deleted) {
      return;
    }
    // Deleting it would leave the stock entry without its expense.
    if (await _expenseDao.isLinkedToStock(idExpense)) {
      throw StateError(
        'This expense was generated by a stock purchase and cannot be deleted.',
      );
    }

    await _expenseDao.softDeleteExpense(idExpense, deletionReason.trim());
  }
}